"""Build a Windows native installer around the standalone PrintPipe bundle."""

from __future__ import annotations

import shlex
import subprocess
import tempfile
import zipfile
from pathlib import Path, PurePosixPath
from typing import Any, Callable

CommandRunner = Callable[[list[str]], subprocess.CompletedProcess[str]]
MAX_STANDALONE_ZIP_MEMBERS = 1_024
MAX_STANDALONE_ZIP_MEMBER_BYTES = 128 * 1024 * 1024
MAX_STANDALONE_ZIP_EXPANDED_BYTES = 512 * 1024 * 1024
MAX_STANDALONE_ZIP_COMPRESSION_RATIO = 100


def build_windows_installer_package(
    *,
    standalone_zip: str | Path,
    output_path: str | Path = Path("dist/PrintPipeSetup.exe"),
    iscc_command: str | list[str] = "iscc",
    signtool_command: str | list[str] = "signtool",
    certificate_subject: str | None = None,
    runner: CommandRunner | None = None,
) -> dict[str, Any]:
    """Build an Inno Setup installer and optionally Authenticode-sign it."""

    source_zip = Path(standalone_zip).expanduser()
    if not source_zip.is_absolute():
        source_zip = Path.cwd() / source_zip
    source_zip = source_zip.resolve()
    if not source_zip.exists():
        raise FileNotFoundError(f"Windows standalone ZIP not found: {source_zip}")
    target = Path(output_path).expanduser()
    if not target.is_absolute():
        target = Path.cwd() / target
    target = target.resolve()
    if target.suffix.lower() != ".exe":
        raise ValueError("Windows installer output must end with .exe")
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        target.unlink()

    run = _run_command if runner is None else runner
    with tempfile.TemporaryDirectory(prefix="printpipe-windows-installer-") as temp_dir:
        temp_root = Path(temp_dir)
        staging = temp_root / "staging"
        staging.mkdir()
        with zipfile.ZipFile(source_zip) as archive:
            _extract_standalone_zip(archive, staging)
        bundle_root = staging / "PrintPipe"
        if not (bundle_root / "PrintPipe.exe").exists():
            raise ValueError("Windows standalone ZIP must contain PrintPipe/PrintPipe.exe")
        script_path = temp_root / "PrintPipe.iss"
        script_path.write_text(
            _inno_script(source_dir=bundle_root, output_path=target),
            encoding="utf-8",
        )
        iscc = _command_parts(iscc_command) + [str(script_path)]
        _run_checked(run, iscc, "Inno Setup build failed")

    if not target.exists():
        raise RuntimeError(f"Inno Setup did not create expected installer: {target}")

    signed = False
    signing_identity = ""
    sign_command: list[str] | None = None
    if certificate_subject:
        sign_command = _command_parts(signtool_command) + [
            "sign",
            "/n",
            certificate_subject,
            "/fd",
            "SHA256",
            "/tr",
            "http://timestamp.digicert.com",
            "/td",
            "SHA256",
            str(target),
        ]
        _run_checked(run, sign_command, "signtool signing failed")
        signed = True
        signing_identity = certificate_subject

    return {
        "status": "ok",
        "installer_path": str(target),
        "installer_name": target.name,
        "installer_kind": "inno_setup",
        "source_standalone_zip": str(source_zip),
        "signed": signed,
        "signing_identity": signing_identity,
        "sign_command": sign_command,
        "bundles_python_runtime": True,
        "bundles_bambu_studio": False,
        "size_bytes": target.stat().st_size,
    }


def _inno_script(*, source_dir: Path, output_path: Path) -> str:
    return f"""; PrintPipe Inno Setup script generated by printpipe
[Setup]
AppId={{{{B516F0B0-9C5A-40C6-A94D-7A08A5E8A001}}}}
AppName=PrintPipe
AppVersion=0.1.0
DefaultDirName={{autopf}}\\PrintPipe
DisableProgramGroupPage=yes
OutputDir={output_path.parent}
OutputBaseFilename={output_path.stem}
Compression=lzma
SolidCompression=yes
PrivilegesRequired=lowest

[Files]
Source: "{source_dir}\\*"; DestDir: "{{app}}"; Flags: ignoreversion recursesubdirs createallsubdirs

[Icons]
Name: "{{autoprograms}}\\PrintPipe"; Filename: "{{app}}\\PrintPipe.exe"

[Run]
Filename: "{{app}}\\PrintPipe.exe"; Parameters: "--version"; Flags: nowait postinstall skipifsilent
"""


def _extract_standalone_zip(archive: zipfile.ZipFile, staging: Path) -> None:
    """Preflight and extract a trusted standalone archive under fixed budgets."""

    infos = archive.infolist()
    if len(infos) > MAX_STANDALONE_ZIP_MEMBERS:
        raise ValueError("Windows standalone ZIP has too many members")
    total_declared = 0
    destinations: set[Path] = set()
    for info in infos:
        _validate_zip_member(info)
        if not info.is_dir():
            total_declared += info.file_size
            if total_declared > MAX_STANDALONE_ZIP_EXPANDED_BYTES:
                raise ValueError("Windows standalone ZIP exceeds expanded byte limit")
        destination = _zip_destination(staging, info.filename)
        if destination in destinations:
            raise ValueError("Windows standalone ZIP contains duplicate paths")
        destinations.add(destination)

    total_written = 0
    for info in infos:
        destination = _zip_destination(staging, info.filename)
        if info.is_dir():
            destination.mkdir(parents=True, exist_ok=True)
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        member_written = 0
        with archive.open(info) as source, destination.open("xb") as target:
            while chunk := source.read(65_536):
                member_written += len(chunk)
                total_written += len(chunk)
                if (
                    member_written > info.file_size
                    or member_written > MAX_STANDALONE_ZIP_MEMBER_BYTES
                    or total_written > MAX_STANDALONE_ZIP_EXPANDED_BYTES
                ):
                    raise ValueError("Windows standalone ZIP exceeds extraction limits")
                target.write(chunk)
        if member_written != info.file_size:
            raise ValueError("Windows standalone ZIP member size changed during extraction")


def _validate_zip_member(info: zipfile.ZipInfo) -> None:
    if info.file_size < 0 or info.file_size > MAX_STANDALONE_ZIP_MEMBER_BYTES:
        raise ValueError("Windows standalone ZIP member exceeds byte limit")
    if not info.is_dir() and info.file_size > 0:
        if (
            info.compress_size <= 0
            or info.file_size
            > info.compress_size * MAX_STANDALONE_ZIP_COMPRESSION_RATIO
        ):
            raise ValueError("Windows standalone ZIP member compression ratio is too high")
    mode = info.external_attr >> 16
    if mode and (mode & 0o170000) == 0o120000:
        raise ValueError("Windows standalone ZIP must not contain symbolic links")
    _zip_destination(Path("."), info.filename)


def _zip_destination(staging: Path, member_name: str) -> Path:
    normalized = member_name.replace("\\", "/")
    path = PurePosixPath(normalized)
    if (
        not normalized
        or path.is_absolute()
        or any(part in {"", ".", ".."} for part in path.parts)
    ):
        raise ValueError("Windows standalone ZIP contains an unsafe member path")
    if any(":" in part for part in path.parts):
        raise ValueError("Windows standalone ZIP contains an unsafe member path")
    destination = staging.joinpath(*path.parts)
    try:
        destination.resolve().relative_to(staging.resolve())
    except ValueError as exc:
        raise ValueError("Windows standalone ZIP member escapes staging") from exc
    return destination


def _command_parts(command: str | list[str]) -> list[str]:
    if isinstance(command, str):
        return shlex.split(command)
    return list(command)


def _run_command(command: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(command, text=True, capture_output=True, check=False)


def _run_checked(
    runner: CommandRunner,
    command: list[str],
    failure_label: str,
) -> subprocess.CompletedProcess[str]:
    result = runner(command)
    if result.returncode != 0:
        message = (result.stderr or result.stdout or failure_label).strip()
        raise RuntimeError(message)
    return result


__all__ = ["build_windows_installer_package"]
