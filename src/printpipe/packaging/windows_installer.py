"""Build a Windows native installer around the standalone PrintPipe bundle."""

from __future__ import annotations

import shlex
import subprocess
import tempfile
import zipfile
from pathlib import Path
from typing import Any, Callable

CommandRunner = Callable[[list[str]], subprocess.CompletedProcess[str]]


def build_windows_installer_package(
    *,
    standalone_zip: str | Path,
    output_path: str | Path = Path("dist/PrintPipeSetup.exe"),
    iscc_command: str | list[str] = "iscc",
    signtool_command: str | list[str] = "signtool",
    certificate_subject: str | None = None,
    runner: CommandRunner | None = None,
) -> dict[str, Any]:
    """Build an Inno Setup installer and optionally Authenticode-sign it."""

    source_zip = Path(standalone_zip).expanduser()
    if not source_zip.is_absolute():
        source_zip = Path.cwd() / source_zip
    source_zip = source_zip.resolve()
    if not source_zip.exists():
        raise FileNotFoundError(f"Windows standalone ZIP not found: {source_zip}")
    target = Path(output_path).expanduser()
    if not target.is_absolute():
        target = Path.cwd() / target
    target = target.resolve()
    if target.suffix.lower() != ".exe":
        raise ValueError("Windows installer output must end with .exe")
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        target.unlink()

    run = _run_command if runner is None else runner
    with tempfile.TemporaryDirectory(prefix="printpipe-windows-installer-") as temp_dir:
        temp_root = Path(temp_dir)
        staging = temp_root / "staging"
        staging.mkdir()
        with zipfile.ZipFile(source_zip) as archive:
            archive.extractall(staging)
        bundle_root = staging / "PrintPipe"
        if not (bundle_root / "PrintPipe.exe").exists():
            raise ValueError("Windows standalone ZIP must contain PrintPipe/PrintPipe.exe")
        script_path = temp_root / "PrintPipe.iss"
        script_path.write_text(
            _inno_script(source_dir=bundle_root, output_path=target),
            encoding="utf-8",
        )
        iscc = _command_parts(iscc_command) + [str(script_path)]
        _run_checked(run, iscc, "Inno Setup build failed")

    if not target.exists():
        raise RuntimeError(f"Inno Setup did not create expected installer: {target}")

    signed = False
    signing_identity = ""
    sign_command: list[str] | None = None
    if certificate_subject:
        sign_command = _command_parts(signtool_command) + [
            "sign",
            "/n",
            certificate_subject,
            "/fd",
            "SHA256",
            "/tr",
            "http://timestamp.digicert.com",
            "/td",
            "SHA256",
            str(target),
        ]
        _run_checked(run, sign_command, "signtool signing failed")
        signed = True
        signing_identity = certificate_subject

    return {
        "status": "ok",
        "installer_path": str(target),
        "installer_name": target.name,
        "installer_kind": "inno_setup",
        "source_standalone_zip": str(source_zip),
        "signed": signed,
        "signing_identity": signing_identity,
        "sign_command": sign_command,
        "bundles_python_runtime": True,
        "bundles_bambu_studio": False,
        "size_bytes": target.stat().st_size,
    }


def _inno_script(*, source_dir: Path, output_path: Path) -> str:
    return f"""; PrintPipe Inno Setup script generated by printpipe
[Setup]
AppId={{{{B516F0B0-9C5A-40C6-A94D-7A08A5E8A001}}}}
AppName=PrintPipe
AppVersion=0.1.0
DefaultDirName={{autopf}}\\PrintPipe
DisableProgramGroupPage=yes
OutputDir={output_path.parent}
OutputBaseFilename={output_path.stem}
Compression=lzma
SolidCompression=yes
PrivilegesRequired=lowest

[Files]
Source: "{source_dir}\\*"; DestDir: "{{app}}"; Flags: ignoreversion recursesubdirs createallsubdirs

[Icons]
Name: "{{autoprograms}}\\PrintPipe"; Filename: "{{app}}\\PrintPipe.exe"

[Run]
Filename: "{{app}}\\PrintPipe.exe"; Parameters: "--version"; Flags: nowait postinstall skipifsilent
"""


def _command_parts(command: str | list[str]) -> list[str]:
    if isinstance(command, str):
        return shlex.split(command)
    return list(command)


def _run_command(command: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(command, text=True, capture_output=True, check=False)


def _run_checked(
    runner: CommandRunner,
    command: list[str],
    failure_label: str,
) -> subprocess.CompletedProcess[str]:
    result = runner(command)
    if result.returncode != 0:
        message = (result.stderr or result.stdout or failure_label).strip()
        raise RuntimeError(message)
    return result


__all__ = ["build_windows_installer_package"]
